/* eslint-disable no-console */
const fs = require('fs');
const path = require('path');

const APP_DIR = path.join(__dirname, '..', 'app');
const OUT_FILE = path.join(__dirname, '..', 'lib', 'voiceRoutes.generated.ts');

const isGroupSegment = (seg) => seg.startsWith('(') && seg.endsWith(')');
const isDynamicSegment = (seg) => seg.startsWith('[') && seg.endsWith(']');

const toTitle = (routePath) => {
  if (routePath === '/') return 'Home';
  const parts = routePath
    .split('/')
    .filter(Boolean)
    .map((p) => p.replace(/[-_]/g, ' '));
  return parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join(' / ');
};

const tokenize = (s) =>
  String(s || '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean);

const collectPages = (dir, relSegments = []) => {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  /** @type {string[]} */
  const routes = [];

  const hasPage = entries.some((e) => e.isFile() && e.name === 'page.tsx');
  if (hasPage) {
    const cleaned = relSegments.filter((s) => !isGroupSegment(s));
    const dynamic = cleaned.some((s) => isDynamicSegment(s));
    if (!dynamic) {
      const routePath = cleaned.length ? `/${cleaned.join('/')}` : '/';
      routes.push(routePath);
    }
  }

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (entry.name.startsWith('.')) continue;
    if (entry.name === 'api') continue;
    routes.push(...collectPages(path.join(dir, entry.name), [...relSegments, entry.name]));
  }

  return routes;
};

const main = () => {
  if (!fs.existsSync(APP_DIR)) {
    console.error('Cannot find app/ directory at', APP_DIR);
    process.exit(1);
  }

  const routePaths = Array.from(new Set(collectPages(APP_DIR))).sort();

  const records = routePaths.map((routePath) => {
    const title = toTitle(routePath);
    const segs = routePath.split('/').filter(Boolean);
    const keywords = Array.from(
      new Set([
        ...tokenize(title),
        ...tokenize(routePath),
        ...segs.flatMap((s) => tokenize(s.replace(/[-_]/g, ' '))),
      ])
    );

    return { path: routePath, title, keywords };
  });

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  const file = `// This file is auto-generated by scripts/generate-voice-routes.js
// Do not edit manually.

export type VoiceRouteRecord = {
  path: string;
  title: string;
  keywords: string[];
};

export const VOICE_ROUTES: VoiceRouteRecord[] = ${JSON.stringify(records, null, 2)} as const;
`;

  fs.writeFileSync(OUT_FILE, file, 'utf8');
  console.log(`[voice-routes] generated ${records.length} routes -> ${path.relative(process.cwd(), OUT_FILE)}`);
};

main();

